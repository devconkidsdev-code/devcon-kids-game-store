// Helper to create grid from ASCII strings for super clean level definitions
function parseGrid(
  ascii: string[],
  charMap: Record<string, TileType>
): TileType[][] {
  return ascii.map(row =>
    row.split('').map(char => charMap[char] || 'grass')
  );
}

